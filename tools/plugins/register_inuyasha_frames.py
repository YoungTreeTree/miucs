#!/usr/bin/env python3
"""Register original model-drawn RGBA cells; never alter sprite pixels."""
import json
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[2]
PACKAGE=ROOT/'plugins/inuyasha'
def register(source,ys,scale,indices=None):
    im=Image.open(PACKAGE/source)
    assert im.mode=='RGBA' and im.getextrema()[3][0]==0
    regions=[]
    pixels=im.getchannel('A').load()
    ys=[0]+[min(range(e-20,e+21),key=lambda y:(sum(pixels[x,yy]>96 for yy in range(y-1,y+2) for x in range(im.width)),abs(y-e))) for e in ys[1:-1]]+[im.height]
    for y0,y1 in zip(ys,ys[1:]):
        xs=[0]
        for c in range(1,4):
            expected=round(c*im.width/4)
            candidates=range(expected-30,expected+31)
            cut=min(candidates,key=lambda x:(sum(pixels[xx,y]>96 for xx in range(x-2,x+3) for y in range(y0,y1)),abs(x-expected)))
            xs.append(cut)
        xs.append(im.width)
        regions.extend([xs[c],y0,xs[c+1]-xs[c],y1-y0] for c in range(4))
    if indices is not None: regions=[regions[i] for i in indices]
    out=dict(source=source,scale=scale,rects=regions,offsets=[],bounds=[],contacts=[])
    for x,y,w,h in regions:
        alpha=im.crop((x,y,x+w,y+h)).getchannel('A').point(lambda a:255 if a>96 else 0)
        l,t,r,b=alpha.getbbox()
        assert l>=1 and t>=1 and r<w and b<h,(source,(x,y,w,h),(l,t,r,b))
        # Ground contact band, not the hair/tail bounds, fixes sprite packing drift.
        band=alpha.crop((0,max(t,b-12),w,b)).getbbox()
        gx=x+round((band[0]+band[2])/2);gy=y+b
        out['contacts'].append([gx,gy]);out['offsets'].append([x-gx,y-gy]);out['bounds'].append([x+l,y+t,x+r,y+b])
    return out

def main():
    data={
        'inuyasha':register('assets/inuyasha.png',[0,325,640,922,1254],.43),
        'kagome':register('assets/kagome.png',[0,334,667,1024],.40),
        'shippo':register('assets/shippo-dust.png',[0,390,760,1086],.25,range(8)),
        'dust':register('assets/shippo-dust.png',[0,390,760,1086],.44,range(8,12)),
    }
    lines=['-- Original pixels, fixed contact registration. Generated by register_inuyasha_frames.py.','return {']
    for name,a in data.items():
        lines.append(f"  {name}={{source='{a['source']}',scale={a['scale']},rects={{")
        lines.extend('    {'+','.join(map(str,v))+'},' for v in a['rects'])
        lines.append('  },offsets={')
        lines.extend('    {'+','.join(map(str,v))+'},' for v in a['offsets'])
        lines.append('  }},')
    lines.append('}')
    (PACKAGE/'frames.lua').write_text('\n'.join(lines)+'\n')
    (ROOT/'docs/concepts/inuyasha/frame-registration.json').write_text(json.dumps(data,indent=2)+'\n')
    print('Registered 16 Inuyasha + 12 Kagome + 8 Shippo + 4 dust frames, original pixels preserved.')
if __name__=='__main__':main()
