#!/usr/bin/env python3
"""Measure generated sprite sheets and write source rectangles, without editing pixels.

Source cells have irregular spacing. Align each frame at its planted feet while
retaining the same pixel scale across all poses. Registration is a build-time
step; Pillow is not a runtime dependency. The original RGBA images stay intact.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / 'plugins/heiji-kazuha'
SHEETS = {
    'heiji': ('heiji-swing.png', [0, 384, 704, 1024]),
    'kazuha': ('kazuha-turn.png', [0, 512, 1024]),
}


def register():
    report = {}
    for name, (filename, rows) in SHEETS.items():
        path = PACKAGE / 'assets' / filename
        im = Image.open(path)
        assert im.mode == 'RGBA' and im.size == (1536, 1024)
        alpha = im.getchannel('A')
        frames = []
        for top, bottom in zip(rows, rows[1:]):
            band = alpha.crop((0, top, 1536, bottom)).point(lambda a: 255 if a > 96 else 0)
            cuts = [0]
            for expected in (384, 768, 1152):
                empty = [x for x in range(expected - 55, expected + 56)
                         if band.crop((x, 0, x + 1, bottom - top)).getbbox() is None]
                assert empty, (name, top, expected, 'no transparent gutter')
                cuts.append((min(empty) + max(empty)) // 2)
            cuts.append(1536)
            for col in range(4):
                left, right = cuts[col], cuts[col + 1]
                # Ignore near-transparent image-generation matte noise. This
                # mask is used only for measurement, never written to an image.
                mask = alpha.crop((left, top, right, bottom)).point(lambda a: 255 if a > 96 else 0)
                bbox = mask.getbbox()
                assert bbox, (name, len(frames))
                x0, y0, x1, y1 = bbox
                assert x0 > 2 and y0 > 2 and x1 < right - left - 2 and y1 < bottom - top - 2, (name, bbox)
                feet = mask.crop((0, y1 - 14, right - left, y1)).getbbox()
                anchor_x = (feet[0] + feet[2]) / 2
                rect = [left + x0 - 2, top + y0 - 2, x1 - x0 + 4, y1 - y0 + 4]
                frames.append({'rect': rect, 'anchor': [anchor_x - x0 + 2, y1 - y0 + 2]})
        report[name] = {'source': 'assets/' + filename, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'frames': frames}
    lines = ['-- Generated by tools/plugins/register_heiji_kazuha.py; original image pixels unchanged.', 'return {']
    for name, data in report.items():
        lines.append(f"  {name}={{source='{data['source']}',frames={{")
        for f in data['frames']:
            lines.append('    {rect={' + ','.join(map(str, f['rect'])) + '},anchor={' + ','.join(map(str, f['anchor'])) + '}},')
        lines.append('  }},')
    lines.append('}')
    (PACKAGE / 'frames.lua').write_text('\n'.join(lines) + '\n')
    (ROOT / 'docs/concepts/heiji-kazuha/registration.json').write_text(json.dumps(report, indent=2) + '\n')
    print('Registered 12 sword poses and 8 turn poses; no image pixels changed')


if __name__ == '__main__':
    register()
